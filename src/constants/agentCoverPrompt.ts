export function excerptAgentPromptForCover(prompt: string, max = 360): string {
  const s = (prompt ?? '').replace(/\s+/g, ' ').trim();
  if (!s) return '';
  if (s.length <= max) return s;
  return `${s.slice(0, max).trimEnd()}…`;
}

export function buildAgentCoverSubject(input: {
  name: string;
  role: string;
  prompt: string;
}): string {
  const name = input.name.trim();
  const role = input.role.trim();
  const excerpt = excerptAgentPromptForCover(input.prompt);
  const parts: string[] = [];
  if (name) parts.push(`角色「${name}」`);
  if (role) parts.push(`身份／专长：${role}`);
  if (excerpt) parts.push(`气质与故事：${excerpt}`);
  if (parts.length === 0) {
    parts.push('一位安静的文学绘本角色，正在思考。');
  }
  parts.push('请把 ta 画成诗集里走出来的绘本角色，而不是助手图标或吉祥物。');
  return parts.join('\n');
}

export function buildAgentCoverPrompt(input: {
  name: string;
  role: string;
  prompt: string;
}): string {
  const name = input.name.trim();
  const subject = buildAgentCoverSubject(input);
  let out = AGENT_COVER_STYLE_PROMPT.replaceAll('{{USER_SUBJECT}}', subject);
  if (name) {
    out = out.replaceAll('{{CHARACTER_NAME}}', name);
  } else {
    out = out.replace(
      '如果用户提供了人物名字：\n人物名字：{{CHARACTER_NAME}}',
      '用户未提供人物名字：画面中不要书写任何文字，也不要印章。',
    );
  }
  return out;
}
